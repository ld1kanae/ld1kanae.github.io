const mergeIds = {
  // 「癪に障る／癪に触る」は表記違い。同じ読みの重複を代表表記へ統合する。
  'jp-000609': 'jp-000072'
};
const mergedPhrases = { '癪に触る': '癪に障る' };

let changed = 0;
let phraseChanges = 0;
for (const filename of fs.readdirSync(dataDir).filter((name) => /^vocabulary_\d{3}\.txt$/.test(name)).sort()) {
  const fullPath = path.join(dataDir, filename);
  const rows = JSON.parse(fs.readFileSync(fullPath, 'utf8'))
    .filter((row) => !mergeIds[row.id])
    .map((row) => ({
      ...row,
      similar: (row.similar || []).map((phrase) => mergedPhrases[phrase] || phrase)
        .filter((phrase, index, all) => phrase !== row.phrase && all.indexOf(phrase) === index)
    }));
  let touched = false;
  for (const row of rows) {
    const fix = fixes[row.id];
    if (!fix) continue;
    if (fix.phrase && fix.phrase !== row.phrase) phraseChanges += 1;
    Object.assign(row, fix);
    changed += 1;
    touched = true;
  }
  if (touched) fs.writeFileSync(fullPath, `${JSON.stringify(rows, null, 2)}\n`);
}

console.log(`修正 ${changed}件（表現名の変更 ${phraseChanges}件）`);
fs.writeFileSync(
  path.join(__dirname, 'semantic_id_aliases.json'),
  `${JSON.stringify(mergeIds, null, 2)}\n`
);
